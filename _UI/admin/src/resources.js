const text = (key, label, max = 128, required = true) => ({
  key,
  label,
  max,
  required,
  type: 'text',
})
const area = (key, label, max) => ({ ...text(key, label, max, false), type: 'textarea' })
const number = (key, label, value = 0, min = 0, precision = 0) => ({
  key,
  label,
  type: 'number',
  default: value,
  min,
  precision,
  required: true,
})
const image = (key, label) => ({ key, label, type: 'image', default: '', full: true })
const select = (key, label, options, defaultValue) => ({
  key,
  label,
  type: 'select',
  options,
  default: defaultValue,
  required: true,
})
const lookup = (key, label, url, name, extra = {}) => ({
  key,
  label,
  type: 'lookup',
  url,
  name,
  required: true,
  ...extra,
})
